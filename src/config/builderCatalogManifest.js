export const UPSTREAM_TEMPLATE_SIGNATURES = new Set(Array.isArray(upstreamData.signatures) ? upstreamData.signatures : []);
export const RETIRED_TEMPLATE_FAMILIES = new Set(Array.isArray(upstreamData.retiredFamilies) ? upstreamData.retiredFamilies : []);

