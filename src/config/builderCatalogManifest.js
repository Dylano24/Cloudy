// Contexts that only retired command files used (botlog/count, gambling/fight, ...).
export const RETIRED_TEMPLATE_CONTEXTS = new Set([...RETIRED_TEMPLATE_FAMILIES]
  .map(family => family.slice(0, family.indexOf('|'))).filter(Boolean));

export function isApprovedFeatureContext(context) {
  const value = String(context || '').trim().toLowerCase();
  return Boolean(value) && APPROVED_CONTEXTS.some(pattern => pattern.test(value));
}

function relativeSourcePath(value) {
  return String(value || '').replace(/\\/g, '/').replace(/^\.?\/?(?:src\/)?/, '');
}

export function isRetiredSourcePath(value) {
  return RETIRED_SOURCE_FILES.has(relativeSourcePath(value));
}

export function isApprovedUpstreamSourcePath(value) {
  const file = relativeSourcePath(value);
  return APPROVED_UPSTREAM_SOURCES.some(pattern => pattern.test(file));
}

/** The source file of a discovered definition (its variantId starts with it). */
export function definitionSourcePath(definition = {}) {
  const variant = String(definition.variantId || '');
  const at = variant.indexOf('.js:');
  return at === -1 ? '' : relativeSourcePath(variant.slice(0, at + 3));
}
