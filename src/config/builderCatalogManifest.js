// Generated by scripts/generate-builder-catalog-upstream.js: the text
// fingerprints of the original TitanBot templates and the template families of
// the retired command files (kept, so they stay archived after the files go).
function readUpstreamData() {
  try {
    return JSON.parse(fs.readFileSync(new URL('./builderCatalogUpstream.json', import.meta.url), 'utf8'));
  } catch {
    return {};
  }
}
